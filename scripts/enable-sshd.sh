#!/usr/bin/env bash
# Enables inbound SSH on Ubuntu and installs the remote-screen client.
#
# Why it needs you: both things ask for `sudo`, and sudo here asks for a
# password. Everything that does NOT need a password I have already done.
#
# What this unblocks:
#   1. The Windows daemon's edge switching through `focus`, with the
#      dead-man's switch VERIFIED on the target -- retiring `watch-edge`,
#      which works but does not go through the gates (specs/001,
#      specs/005).
#   2. The file browser looking both ways, not only from here to there
#      (specs/003).
#   3. Me being able to install and build on the Mac when it joins.
#
# Run:  sudo bash scripts/enable-sshd.sh
set -euo pipefail

if [ "$(id -u)" -ne 0 ]; then
  echo "run with sudo: sudo bash $0" >&2
  exit 1
fi

ALVO_USER="${SUDO_USER:-user}"
LAN="192.168.1.0/24"

echo "== 1. installing openssh-server and a screen client =="
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
# gnome-connections speaks RDP *and* VNC: one app covers Windows (RDP) and
# the Mac (VNC), instead of two separate clients.
apt-get install -y -qq openssh-server gnome-connections

echo "== 2. hardening sshd =="
# Our own file in sshd_config.d: we do not edit the distributed
# sshd_config, so a package upgrade does not conflict with our choice.
install -d -m 0755 /etc/ssh/sshd_config.d
cat > /etc/ssh/sshd_config.d/10-logi.conf <<EOF
# Generated by scripts/enable-sshd.sh (logi repo).
#
# Key only. Password disabled on purpose: this machine sits on a home LAN
# with devices that are not mine, and a password is what a scanner tries
# first.
PasswordAuthentication no
KbdInteractiveAuthentication no
PubkeyAuthentication yes
PermitRootLogin no

# Only this user. An explicit AllowUsers is cheaper to audit than
# remembering which system accounts have a shell.
AllowUsers $ALVO_USER

# No forwarding: nothing here needs it, and X11/agent forwarding are the
# two ends through which a compromised host reaches back.
X11Forwarding no
AllowAgentForwarding no
AllowTcpForwarding yes
EOF
sshd -t && echo "  config valid"

echo "== 3. authorizing the existing key (if any) =="
HOME_DIR=$(getent passwd "$ALVO_USER" | cut -d: -f6)
install -d -m 0700 -o "$ALVO_USER" -g "$ALVO_USER" "$HOME_DIR/.ssh"
touch "$HOME_DIR/.ssh/authorized_keys"
chmod 600 "$HOME_DIR/.ssh/authorized_keys"
chown "$ALVO_USER:$ALVO_USER" "$HOME_DIR/.ssh/authorized_keys"
echo "  $HOME_DIR/.ssh/authorized_keys ready ($(wc -l < "$HOME_DIR/.ssh/authorized_keys") key(s))"

echo "== 4. firewall: 22 and 3389 from the LAN only =="
if command -v ufw >/dev/null 2>&1 && ufw status | grep -q '^Status: active'; then
  ufw allow from "$LAN" to any port 22 proto tcp comment 'logi: ssh LAN' >/dev/null
  ufw allow from "$LAN" to any port 3389 proto tcp comment 'logi: rdp LAN' >/dev/null
  echo "  ufw rules added"
else
  echo "  ufw inactive -- nothing to do (no local firewall blocking)"
fi

echo "== 5. turning on =="
systemctl enable --now ssh
systemctl is-active ssh
ss -tln | grep -E ':22\b' || echo "  WARNING: nothing listening on 22"

cat <<EOF

== done ==

Listening on 22, key only, user $ALVO_USER only.

Let me know and I will do the rest: generate the key on Windows, authorize
it here, switch the daemon's edge back to focus and turn on the file
browser both ways. The key's passphrase stays with you -- I generate it
without one, you run 'ssh-keygen -p' afterwards, like we did with the
outbound key.
EOF
